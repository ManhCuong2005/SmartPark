  @override
  void paint(Canvas canvas, Size size) {
    canvas.save();
    canvas.scale(size.width / 198);
    final paint = Paint()..color = ParkColors.navy;
    for (final p in modules) {
      canvas.drawRRect(
        RRect.fromRectAndRadius(
          Rect.fromLTWH(p.dx, p.dy, 10.2, 10.2),
          const Radius.circular(1.4),
        ),
        paint,
      );
    }
    canvas.restore();
  }

